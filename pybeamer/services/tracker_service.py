from typing import Any

from ..models import Project, User, Tracker, Baseline, Field, FieldDefinition, ChoiceValue, TrackerItem
from ..api_client import APIClient

IntoTracker = str | int | Tracker

class TrackerService:
	"""Service layer for Tracker REST operations."""

	def __init__(self, client: APIClient):
		self._client = client

	##################
	# Default Method #
	##################
	def __call__(self, *, project: str | int = None) -> list[Project]:
		if project:
			return self.get_project(project)
		return self.get_projects()

	############
	# Trackers #
	############
	def get_configuration(self, traker: IntoTracker) -> dict[str, Any]: ...
	def create_or_update_configuration(self, tracker: IntoTracker, **kwargs): ...
	def delete_tracker(self, tracker: IntoTracker): ...
	def get_tracker(self, tracker: IntoTracker) -> Tracker | None: ...
	def get_tracker_by_name(self, name: str) -> Tracker | None: ...
	def get_tracker_by_id(self, id: int) -> Tracker | None: ...
	def update_tracker(self, tracker: IntoTracker, **updates): ...
	def get_tracker_baselines(self, tracker: IntoTracker) -> list[Baseline]: ...
	def get_tracker_fields(self, tracker: IntoTracker) -> list[Field]: ...
	def get_tracker_field(self, tracker: IntoTracker, field: str | int | FieldDefinition) -> Field | None: ...
	def get_tracker_field_by_name(self, tracker: IntoTracker, name: str) -> Field | None: ...
	def get_tracker_field_by_id(self, tracker: IntoTracker, id: int) -> Field | None: ...
	def get_tracker_field_options(self, tracker: IntoTracker, field: str | int | FieldDefinition | Field) -> list[ChoiceValue]: ...
	def get_tracker_field_permissions(self, tracker: IntoTracker, field: str | int | FieldDefinition | Field) -> list[dict[str, Any]]: ... # TODO: Permissions
	def get_tracker_fields_permissions(self, tracker: IntoTracker) -> list[dict[str, Any]]: ... # TODO: Permissions
	def update_tracker_icon(self, tracker: IntoTracker, **kwargs): ...
	def get_tracker_items(self, tracker: IntoTracker) -> list[TrackerItem]: ...
	def get_tracker_outline(self, tracker: IntoTracker) -> list[dict[str, Any]]: ... # TODO: Outline
	def get_tracker_schema(self, tracker: IntoTracker) -> list[dict[str, Any]]: ... # TODO: Schema
	def get_tracker_transitions(self, tracker: IntoTracker) -> list[dict[str, Any]]: ... # TODO: Transition
	def get_tracker_types(self) -> list[dict[str, Any]]: ... # TODO: TrackerType
