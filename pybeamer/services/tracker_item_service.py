from ..api_client import APIClient
from ..models import Tracker, TrackerItem, Field

TrackerLike = str | int | Tracker
ItemLike = str | int | TrackerItem
FieldLike = str | int | Field

class TrackerItemService:
	"""Service layer for Tracker Item REST operations."""

	def __init__(self, client: APIClient):
		self._client = client

	#############
	# Endpoints #
	#############
	# DELETE /v3/items/{itemId}
	def delete_item(self, item: ItemLike): ...
	# GET /v3/items/{itemId}
	def get_item(self, item: ItemLike) -> TrackerItem | None: ...
	# PUT /v3/items/{itemId}
	def update_item(self, item: ItemLike, **kwargs): ... # TODO: args
	# GET /v3/items/{itemId}/children
	def get_item_children(self, item: ItemLike) -> list[TrackerItem]: ...
	# PATCH /v3/items/{itemId}/children
	def patch_item_children(self, item: ItemLike, **kwargs): ...
	# POST /v3/items/{itemId}/children
	def add_item_child(self, item: ItemLike, **kwargs): ...
	# PUT /v3/items/{itemId}/children
	def replace_item_child(self, item: ItemLike, **kwargs): ...
	# GET /v3/items/{itemId}/fields
	def get_item_fields(self, item: ItemLike): ...
	# PUT /v3/items/{itemId}/fields
	def update_item_fields(self, item: ItemLike, **kwargs): ...
	# GET /v3/items/{itemId}/fields/{fieldId}/options
	def get_item_field_options(self, item: ItemLike, field: FieldLike): ...
	# GET /v3/items/{itemId}/fields/accessibility
	def get_item_field_accessibility(self, item: ItemLike): ...
	# PUT /v3/items/{itemId}/fields/tables/{tableFieldId}
	def update_item_table_field(self, item: ItemLike, **kwargs): ...
	# GET /v3/items/{itemId}/history
	def get_item_history(self, item: ItemLike): ...
	# DELETE /v3/items/{itemId}/lock
	def unlock_item(self, item: ItemLike): ...
	# GET /v3/items/{itemId}/lock
	def get_item_lock(self, item: ItemLike): ...
	# PUT /v3/items/{itemId}/lock
	def lock_item(self, item: ItemLike): ...
	# GET /v3/items/{itemId}/relations
	def get_item_relations(self, item: ItemLike): ...
	# GET /v3/items/{itemId}/reviews
	def get_item_reviews(self, item: ItemLike): ...
	# GET /v3/items/{itemId}/transitions
	def get_item_transitions(self, item: ItemLike): ...
	# PUT /v3/items/fields
	def bulk_update_item_fields(self, item: ItemLike, *fields: Field): ...
