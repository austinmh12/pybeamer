	def query_items(self, cbql: str) -> list[TrackerItem]: ... #? This has a GET and POST, this will use the  POST
	# POST /v3/items/relations
	def get_related_item(self, *items: ItemLike): ...
	#! The rest are rooted at /v3/trackers but are categorized under Tracker Items in the swagger file.
	# GET /v3/trackers/{trackerId}/children
	def get_tracker_items(self, tracker: TrackerLike) -> list[TrackerItem]: ...
	# PATCH /v3/trackers/{trackerId}/children
	def patch_tracker_items(self, tracker: TrackerLike, **kwargs): ...
	# POST /v3/trackers/{trackerId}/children
	def add_item_to_tracker(self, tracker: TrackerLike, item: ItemLike): ...
	# PUT /v3/trackers/{trackerId}/children
	def reorder_tracker_children(self, tracker: TrackerLike, **kwargs): ...
	# POST /v3/trackers/{trackerId}/items
