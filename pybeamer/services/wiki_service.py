from ..api_client import APIClient
from ..models import Project, TrackerItem

ProjectLike = str | int | Project
ItemLike = str | int | TrackerItem

class WikiService:
	"""Service layer for Wiki REST operations."""

	def __init__(self, client: APIClient):
		self._client = client

	#############
	# Endpoints #
	#############
	# POST /v3/projects/{projectId}/wiki2html
	def render_wikipage_as_html(self, project: ProjectLike, **kwargs): ...
	# POST /v3/wikipages
	def create_wikipage(self, **kwargs): ...
	# PUT /v3/wikipages/{itemId}
	def update_or_move_wikipage(self, item: ItemLike, **kwargs): ...
	# DELETE /v3/wikipages/{wikiId}
	def delete_wikipage(self, wikipage: int): ...
	# GET /v3/wikipages/{wikiId}
	def get_wikipage(self, wikipage: int): ...
	# GET /v3/wikipages/{wikiId}/history
	def get_wikipage_history(self, wikipage: int): ...
	# GET /v3/wikipages/{wikiId}/html
	def get_wikipage_html(self, wikipage: int): ...
	# DELETE /v3/wikipages/{wikiId}/lock
	def unlock_wikipage(self, wikipage: int): ...
	# GET /v3/wikipages/{wikiId}/lock
	def get_wikipage_lock(self, wikipage: int): ...
	# PUT /v3/wikipages/{wikiId}/lock
	def lock_wikipage(self, wikipage: int): ...
	# GET /v3/wikipages/{wikiId}/permissions
	def get_wikipage_permissions(self, wikipage: int): ...
	# PUT /v3/wikipages/{wikiId}/permissions
	def update_wikipage_permissions(self, wikipage: int, **kwargs): ...
	# PUT /v3/wikipages/{wikiId}/restorecontent
	def restore_wikipage_content(self, wikipage: int, **kwargs): ...